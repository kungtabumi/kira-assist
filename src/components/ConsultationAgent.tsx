/**
 * Helper function in ConsultationAgent that cross-references user contextual queries
 * against 'BUSINESS_PROFILES' and 'PRODUCT_CATALOG' data to automatically fetch
 * and append relevant product links or IDs to the AI's response when relevant.
 *
 * @param userQuery The contextual inquiry or styling request from the user
 * @param aiResponseContent The text response generated by the AI
 * @param existingRecommendation Optional recommendation already attached to the AI response
 * @param businessProfiles List of business profiles (defaults to BUSINESS_PROFILES)
 * @param productCatalog Collection of catalog products (defaults to PRODUCT_CATALOG)
 * @returns Object with enrichedContent containing appended product links/IDs and matched product list
 */
export function crossReferenceContextualProducts(
  userQuery: string,
  aiResponseContent: string,
  existingRecommendation?: AgentRecommendation,
  businessProfiles: BusinessProfile[] = BUSINESS_PROFILES,
  productCatalog: ProductItem[] = PRODUCT_CATALOG
): {
  enrichedContent: string;
  matchedProducts: ProductItem[];
  attachedProductIds: string[];
} {
  const qLower = (userQuery || '').toLowerCase().trim();
  const resLower = (aiResponseContent || '').toLowerCase().trim();

  // If both query and content are empty, return unmodified
  if (!qLower && !resLower) {
    return {
      enrichedContent: aiResponseContent,
      matchedProducts: [],
      attachedProductIds: []
    };
  }

  // Cross-reference against BUSINESS_PROFILES
  const activeProfile =
    businessProfiles.find(b => b.id === 'OERIP') ||
    businessProfiles.find(b => b.is_active_pilot) ||
    businessProfiles[0] || {
      id: 'OERIP',
      name: 'Oerip Indonesia',
      founder: 'Dian Errakumalasari (Dian Oerip)',
      city: 'Ngawi, Jawa Timur',
      tagline: 'Living Heritage, Zero-Waste Etnik Kontemporer',
      description: 'Jenama fesyen etnik kontemporer dan berkelanjutan',
      is_active_pilot: true,
      verified_socials: ['@oerip_official', '@dian_oerip']
    };

  // Check if query is explicitly asking for product recommendations, buying, or catalog showcase
  // Stricter check: Do NOT assume informational, cultural, or small-talk queries want product recommendations
  const isInformationalQuery =
    qLower.includes('apa itu') ||
    qLower.includes('itu apa') ||
    qLower.includes('makna') ||
    qLower.includes('filosofi') ||
    qLower.includes('sejarah') ||
    qLower.includes('asal usul') ||
    qLower.includes('ceritakan') ||
    qLower.includes('siapa') ||
    qLower.includes('bagaimana') ||
    qLower.includes('cuci') ||
    qLower.includes('merawat') ||
    qLower.includes('lerak') ||
    qLower.includes('zero waste') ||
    qLower.includes('zero-waste') ||
    qLower.includes('minim potong') ||
    qLower.includes('slow fashion') ||
    qLower.includes('kapasitas') ||
    qLower.includes('halo') ||
    qLower.includes('selamat');

  const isExplicitProductSeeking =
    qLower.includes('rekomendasi') ||
    qLower.includes('rekomendasikan') ||
    qLower.includes('saran baju') ||
    qLower.includes('saran busana') ||
    qLower.includes('saran outfit') ||
    qLower.includes('pilihan baju') ||
    qLower.includes('pilihan busana') ||
    qLower.includes('pilihan outfit') ||
    qLower.includes('katalog') ||
    qLower.includes('daftar produk') ||
    qLower.includes('beli baju') ||
    qLower.includes('beli busana') ||
    qLower.includes('beli pakaian') ||
    qLower.includes('mau beli') ||
    qLower.includes('mau pesan') ||
    qLower.includes('order baju') ||
    qLower.includes('pesan baju') ||
    qLower.includes('cari baju') ||
    qLower.includes('cari busana') ||
    qLower.includes('cari outfit') ||
    qLower.includes('butuh rekomendasi') ||
    qLower.includes('minta rekomendasi') ||
    qLower.includes('cocok pakai apa') ||
    qLower.includes('pakai baju apa') ||
    qLower.includes('padu padan') ||
    qLower.includes('styling') ||
    qLower.includes('traveling') ||
    qLower.includes('pantai') ||
    qLower.includes('resort') ||
    qLower.includes('liburan');

  const isContextuallySeekingProducts = !isInformationalQuery && isExplicitProductSeeking;

  // Score each product in PRODUCT_CATALOG based on contextual matches
  const scoredProducts = productCatalog.map(product => {
    let score = 0;
    const pIdLower = product.product_id.toLowerCase();
    const pNameLower = product.product_name.toLowerCase();
    const pTextileLower = product.textile.toLowerCase();
    const pOriginLower = product.textile_origin.toLowerCase();
    const pCategoryLower = product.category.toLowerCase();
    const pMotifLower = product.motif.toLowerCase();
    const pOccasions = (product.occasion || []).map(o => o.toLowerCase());

    // 1. Exact Product ID mention in Query (+100) or in AI response (+40)
    if (qLower.includes(pIdLower)) score += 100;
    if (resLower.includes(pIdLower)) score += 40;

    // 2. Product Name / Title Keywords
    const nameTokens = pNameLower.split(/[\s\/\(\)]+/).filter(t => t.length > 3 && !['oerip', 'with', 'heritage'].includes(t));
    for (const token of nameTokens) {
      if (qLower.includes(token)) score += 20;
      if (resLower.includes(token)) score += 8;
    }

    // 3. Wastra / Textile Type & Geographic Origin Matches
    const origins = ['sumba', 'tuban', 'gedog', 'lurik', 'klaten', 'ulos', 'batak', 'toba', 'toraja', 'flores', 'ende'];
    for (const origin of origins) {
      if (pTextileLower.includes(origin) || pOriginLower.includes(origin)) {
        if (qLower.includes(origin)) score += 35;
        if (resLower.includes(origin)) score += 15;
      }
    }

    // 4. Garment Form Matches
    const garments = [
      { key: 'blanket', term: 'blanket' },
      { key: 'outer', term: 'outer' },
      { key: 'kimono', term: 'kimono' },
      { key: 'duster', term: 'duster' },
      { key: 'robe', term: 'robe' },
      { key: 'vest', term: 'vest' },
      { key: 'rompi', term: 'vest' },
      { key: 'cape', term: 'cape' },
      { key: 'wrap', term: 'wrap' },
      { key: 'dress', term: 'dress' },
      { key: 'tunik', term: 'tunic' },
      { key: 'tunic', term: 'tunic' },
      { key: 'poncho', term: 'poncho' },
      { key: 'selendang', term: 'selendang' }
    ];
    for (const g of garments) {
      if (pCategoryLower.includes(g.term) || pNameLower.includes(g.term)) {
        if (qLower.includes(g.key)) score += 25;
        if (resLower.includes(g.key)) score += 10;
      }
    }

    // 5. Occasion Alignment
    for (const occ of pOccasions) {
      if (qLower.includes('diplomasi') && occ.includes('diplomasi')) score += 30;
      if ((qLower.includes('kondangan') || qLower.includes('resepsi') || qLower.includes('pernikahan') || qLower.includes('pesta')) && (occ.includes('resepsi') || occ.includes('formal') || occ.includes('resmi'))) score += 25;
      if ((qLower.includes('kantor') || qLower.includes('kerja') || qLower.includes('smart-casual') || qLower.includes('meeting')) && (occ.includes('kantor') || occ.includes('smart-casual'))) score += 25;
      if ((qLower.includes('reuni') || qLower.includes('kafe') || qLower.includes('santai') || qLower.includes('hangout') || qLower.includes('kasual')) && (occ.includes('santai') || occ.includes('harian') || occ.includes('smart-casual') || occ.includes('bohemian'))) score += 20;
      if ((qLower.includes('wisuda') || qLower.includes('akademik')) && (occ.includes('resmi') || occ.includes('kebudayaan') || occ.includes('formal'))) score += 20;
      if ((qLower.includes('travel') || qLower.includes('jalan') || qLower.includes('liburan') || qLower.includes('pantai') || qLower.includes('resort') || qLower.includes('pesisir')) && (occ.includes('traveling') || occ.includes('bohemian') || occ.includes('resort'))) score += 35;
      if ((qLower.includes('keluarga') || qLower.includes('arisan') || qLower.includes('silaturahmi')) && (occ.includes('keluarga') || occ.includes('resmi'))) score += 25;
    }

    // 6. Motif Matches
    if ((qLower.includes('kuda') || qLower.includes('njara')) && pMotifLower.includes('kuda')) score += 30;
    if (qLower.includes('ganggeng') && pMotifLower.includes('ganggeng')) score += 30;
    if ((qLower.includes('kerbau') || qLower.includes('teddong')) && pMotifLower.includes('teddong')) score += 30;
    if (qLower.includes('bolo') && pMotifLower.includes('bolo')) score += 30;

    // 7. Size, Fit & Silhouette Matches
    if ((qLower.includes('badan besar') || qLower.includes('ukuran') || qLower.includes('ld') || qLower.includes('gemuk')) && product.size.toLowerCase().includes('loose')) {
      score += 20;
    }

    // 8. Budget & Price Queries
    if ((qLower.includes('murah') || qLower.includes('terjangkau') || qLower.includes('hemat') || qLower.includes('budget')) && (product.product_id === 'OERIP-LUR-003' || product.product_id === 'OERIP-VES-008')) {
      score += 35;
    }

    return { product, score };
  });

  // Filter products with meaningful score and sort descending
  const relevantMatches = scoredProducts
    .filter(item => item.score >= 20)
    .sort((a, b) => b.score - a.score)
    .map(item => item.product);

  // If no specific match scored >= 20, but query is seeking general products, fall back to flagship product
  const finalMatchedProducts: ProductItem[] =
    relevantMatches.length > 0
      ? relevantMatches.slice(0, 3)
      : isContextuallySeekingProducts
      ? [productCatalog[0]]
      : [];

  // Determine if we should append product links / IDs to the response content
  // Guardrail refusal, out of domain, or small talk/greetings should not append catalog products
  const isGuardrailOrOutOfDomain =
    resLower.includes('rahasia perusahaan') ||
    resLower.includes('restricted enterprise') ||
    resLower.includes('di luar domain') ||
    resLower.includes('pustaka budaya belum tersedia') ||
    resLower.includes('selamat datang di **kira**') ||
    resLower.includes('saya adalah **kira**') ||
    resLower.includes('kabar baik, sehat, dan senantiasa penuh semangat') ||
    resLower.includes('terima kasih kembali, sahabat budaya') ||
    resLower.includes('siap, sahabat budaya! kira aktif') ||
    resLower.includes('layanan & kapabilitas kira') ||
    resLower.includes('tidak memilih produk secara acak') ||
    resLower.includes('belum spesifik') ||
    resLower.includes('klarifikasi') ||
    !isContextuallySeekingProducts;

  if (finalMatchedProducts.length === 0 || isGuardrailOrOutOfDomain) {
    return {
      enrichedContent: aiResponseContent,
      matchedProducts: finalMatchedProducts,
      attachedProductIds: finalMatchedProducts.map(p => p.product_id)
    };
  }

  // Check if product links / IDs are already clearly formatted in aiResponseContent
  const alreadyHasAppendedLinks =
    aiResponseContent.includes('Referensi Koleksi & Katalog Resmi Terkait') ||
    aiResponseContent.includes('Referensi Produk & Katalog Resmi') ||
    aiResponseContent.includes('Katalog Produk Terkait:');

  // Check which products are not yet mentioned with ID in the content
  const unmentionedProducts = finalMatchedProducts.filter(
    p => !aiResponseContent.includes(p.product_id)
  );

  let enrichedContent = aiResponseContent;

  if (!alreadyHasAppendedLinks && isContextuallySeekingProducts) {
    const productsToAppend = unmentionedProducts.length > 0 ? unmentionedProducts : finalMatchedProducts.slice(0, 2);

    if (productsToAppend.length > 0) {
      const productLinkLines = productsToAppend.map(prod => {
        const cleanName = prod.product_name.replace(/[\(\)]/g, '');
        const cleanId = prod.product_id.replace(/[\(\)]/g, '');
        const waText = encodeURIComponent(
          `Halo Tim Kurasi Oerip Indonesia, saya tertarik dengan koleksi: ${cleanName} [ID: ${cleanId}]. Mohon info detail ketersediaan fisik dan panduan pemesanannya.`
        ).replace(/\(/g, '%28').replace(/\)/g, '%29');
        const waUrl = `https://wa.me/6285174485581?text=${waText}`;
        return `• **${prod.product_name}** \`[ID: ${prod.product_id}]\` — *${prod.textile}* (${prod.price_range})\n  🔗 [Konsultasi WhatsApp Resmi](${waUrl}) • *Kategori: ${prod.category}*`;
      });

      const catalogSection =
        `\n\n---\n\n` +
        `📦 **Referensi Koleksi & Katalog Resmi Terkait (${activeProfile.name}):**\n` +
        productLinkLines.join('\n\n') +
        `\n\n*💡 Seluruh busana Oerip dirancang All-Size Loose Fit (Zero-Waste). Hubungi WhatsApp Admin untuk konfirmasi stok helai aktual.*`;

      enrichedContent = `${aiResponseContent.trim()}${catalogSection}`;
    }
  }

  return {
    enrichedContent,
    matchedProducts: finalMatchedProducts,
    attachedProductIds: finalMatchedProducts.map(p => p.product_id)
  };
}

