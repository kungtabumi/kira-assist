// Helper to render formatted editorial text with headings, bolding, lists, and dividers
const FormattedEditorialText: React.FC<{ content: string }> = ({ content }) => {
  const lines = content.split('\n');

  const renderInlineStyles = (text: string) => {
    // Tokenize by links [label](url), code `...`, bold **...**, italic *...*
    const regex = /(\[.*?\]\(https?:\/\/[^\s\)]+\)|`.*?`|\*\*.*?\*\*|\*.*?\*)/g;
    const parts = text.split(regex);

    return parts.map((part, index) => {
      if (!part) return null;

      // Link: [Label](url)
      const linkMatch = part.match(/^\[(.*?)\]\((https?:\/\/[^\s\)]+)\)$/);
      if (linkMatch) {
        const label = linkMatch[1];
        const url = linkMatch[2];
        const isWa = url.includes('wa.me') || url.includes('whatsapp');
        return (
          <a
            key={index}
            href={url}
            target="_blank"
            rel="noopener noreferrer"
            className={`inline-flex items-center gap-1 font-semibold underline underline-offset-2 transition-colors ${
              isWa
                ? 'text-[#1E3A2B] hover:text-[#2E5942] bg-[#E8F3ED] hover:bg-[#D5EADB] px-1.5 py-0.5 rounded text-[11px]'
                : 'text-[#963824] hover:text-[#7A2D1D]'
            }`}
          >
            <span>{label}</span>
            <ArrowUpRight size={11} className="shrink-0" />
          </a>
        );
      }

      // Code: `code`
      if (part.startsWith('`') && part.endsWith('`') && part.length >= 2) {
        return (
          <code
            key={index}
            className="px-1.5 py-0.5 rounded bg-[#F5EFE6] border border-[#E7DFD5] text-[#963824] font-mono text-[11px] font-semibold"
          >
            {part.slice(1, -1)}
          </code>
        );
      }

      // Bold: **bold**
      if (part.startsWith('**') && part.endsWith('**')) {
        return (
          <strong key={index} className="font-semibold text-[#1C1917] tracking-tight">
            {part.slice(2, -2)}
          </strong>
        );
      }

      // Italic: *italic*
      if (part.startsWith('*') && part.endsWith('*') && !part.startsWith('**')) {
        return (
          <em key={index} className="italic text-[#57534E] font-serif">
            {part.slice(1, -1)}
          </em>
        );
      }

      return part;
    });
  };

  return (
    <div className="space-y-2 text-xs sm:text-sm leading-relaxed text-[#2D2A26]">
      {lines.map((line, idx) => {
        const trimmed = line.trim();
        if (!trimmed) {
          return <div key={idx} className="h-1" />;
        }

        // Header 3: ### ...
        if (trimmed.startsWith('### ')) {
          const headerText = trimmed.replace('### ', '');
          return (
            <div key={idx} className="pt-2 pb-1 border-b border-[#E7DFD5]">
              <h4 className="font-serif font-bold text-sm sm:text-base text-[#1C1917] tracking-tight flex items-center gap-1.5">
                <span className="text-[#963824] text-xs">✦</span>
                <span>{renderInlineStyles(headerText)}</span>
              </h4>
            </div>
          );
        }

        // Header 2 or 1: ## ... or # ...
        if (trimmed.startsWith('## ') || trimmed.startsWith('# ')) {
          return (
            <div key={idx} className="pt-2.5 pb-1 border-b border-[#E7DFD5]">
              <h3 className="font-serif font-bold text-base sm:text-lg text-[#1C1917] tracking-tight flex items-center gap-2">
                <span className="w-2 h-2 rounded-full bg-[#963824]"></span>
                <span>{renderInlineStyles(trimmed.replace(/^#+\s*/, ''))}</span>
              </h3>
            </div>
          );
        }

        // Horizontal Rule
        if (trimmed === '---' || trimmed === '***') {
          return (
            <div key={idx} className="my-2.5 flex items-center justify-center gap-3">
              <span className="h-px bg-[#E7DFD5] flex-1"></span>
              <span className="text-[#C89B53] text-xs font-serif">❦</span>
              <span className="h-px bg-[#E7DFD5] flex-1"></span>
            </div>
          );
        }

        // List item: bullet (•, -, *)
        if (trimmed.startsWith('• ') || trimmed.startsWith('- ') || trimmed.startsWith('* ')) {
          const listText = trimmed.replace(/^[•\-\*]\s*/, '');
          return (
            <div key={idx} className="flex items-start gap-2 pl-1 sm:pl-2">
              <span className="text-[#963824] text-xs mt-1 shrink-0">◆</span>
              <div className="flex-1 leading-relaxed">{renderInlineStyles(listText)}</div>
            </div>
          );
        }

        // Numbered list item: 1. ... or 1) ...
        const numberedMatch = trimmed.match(/^(\d+)[\.\)]\s+(.*)/);
        if (numberedMatch) {
          const num = numberedMatch[1];
          const text = numberedMatch[2];
          return (
            <div key={idx} className="flex items-start gap-2 pl-1 sm:pl-2 py-0.5">
              <span className="w-4 h-4 rounded-full bg-[#F5EFE6] border border-[#E7DFD5] text-[#963824] font-serif font-bold text-[10px] flex items-center justify-center shrink-0 mt-0.5">
                {num}
              </span>
              <div className="flex-1 leading-relaxed">{renderInlineStyles(text)}</div>
            </div>
          );
        }

        // Regular paragraph
        return (
          <p key={idx} className="leading-relaxed">
            {renderInlineStyles(line)}
          </p>
        );
      })}
    </div>
  );
};

